"""Response Agent — determines operational response based on confirmed triage result.

Receives the TriageResult and generates specific, actionable response steps
tied directly to the confirmed attack path.
"""
from __future__ import annotations

from typing import Any

from quallki_agentic.agents.base_agent import BaseAgent
from quallki_agentic.progress import Status, get_progress_logger
from quallki_agentic.result_models import ResponseResult


class ResponseAgent(BaseAgent):
    name = "response"

    def run(self, payload: dict[str, Any]) -> dict[str, Any]:
        logger = get_progress_logger()
        incident_id = str(payload.get("incident_id", "INC-000"))

        logger.emit(incident_id, "response", "response_planning", Status.RUNNING,
                     "Response Agent: Determining operational response actions")

        # ── Read triage result ──────────────────────────────────────────
        triage_result = payload.get("triage_result", {})
        if not isinstance(triage_result, dict):
            triage_result = {}

        confirmed_attack = triage_result.get("confirmed_attack", {})
        if not isinstance(confirmed_attack, dict):
            confirmed_attack = {}

        category = str(confirmed_attack.get("category", "unknown"))
        mechanism = str(confirmed_attack.get("mechanism", "unknown"))
        attack_path = confirmed_attack.get("attack_path", [])
        affected_assets = triage_result.get("affected_assets", [])
        evidence = triage_result.get("evidence", [])
        impact = triage_result.get("impact", {})

        # ── Generate response via LLM ───────────────────────────────────
        logger.emit(incident_id, "response", "response_generation", Status.RUNNING,
                     "Generating response actions based on confirmed attack path")

        from quallki_agentic.llm_helper import invoke_llm

        prompt = f"""You are a Security Operations Center Response Agent.

Based on the confirmed triage analysis, determine the specific operational
response actions. Each action must be directly tied to the confirmed attack path.

## Confirmed Incident
- Incident ID: {incident_id}
- Attack Category: {category}
- Attack Mechanism: {mechanism}
- Attack Path: {attack_path}
- Affected Assets: {affected_assets}
- Evidence: {evidence}
- Impact: {impact}

## Required Output
Return strict JSON with these keys:
- confirmed_attack_summary: string (brief 1-2 sentence summary of the confirmed attack)
- response_actions: list of strings (ordered, specific operational response steps)
- containment_steps: list of strings (immediate containment measures)
- recovery_steps: list of strings (steps to restore normal operations)
- monitoring_recommendations: list of strings (ongoing monitoring recommendations)
"""

        parsed = invoke_llm(prompt, agent_name="response")

        if parsed:
            logger.emit(incident_id, "response", "response_generation", Status.COMPLETED,
                         "Response actions generated by LLM")

            response_result = ResponseResult(
                incident_id=incident_id,
                confirmed_attack_summary=str(parsed.get("confirmed_attack_summary",
                    f"Confirmed {category} attack via {mechanism}")),
                response_actions=[str(a) for a in parsed.get("response_actions", [])],
                containment_steps=[str(s) for s in parsed.get("containment_steps", [])],
                recovery_steps=[str(s) for s in parsed.get("recovery_steps", [])],
                monitoring_recommendations=[str(m) for m in parsed.get("monitoring_recommendations", [])],
            )
        else:
            # Build deterministic response when LLM is unavailable
            logger.emit(incident_id, "response", "response_generation", Status.COMPLETED,
                         "Response actions generated (deterministic)")

            actions = self._deterministic_actions(category, mechanism, affected_assets)
            response_result = ResponseResult(
                incident_id=incident_id,
                confirmed_attack_summary=f"Confirmed {category} attack via {mechanism}",
                response_actions=actions,
                containment_steps=[actions[0]] if actions else ["Isolate affected systems"],
                recovery_steps=["Restore from known-good backup", "Verify system integrity"],
                monitoring_recommendations=["Continue monitoring for recurrence"],
            )

        logger.emit(incident_id, "response", "response_planning", Status.COMPLETED,
                     f"Response Agent completed — {len(response_result.response_actions)} actions generated")

        return {"response_result": response_result.model_dump()}

    @staticmethod
    def _deterministic_actions(category: str, mechanism: str, affected_assets: list) -> list[str]:
        """Generate basic response actions when LLM is unavailable."""
        actions = []
        cat = category.lower()
        if cat in ("dos", "ddos"):
            actions = [
                "Rate-limit the affected endpoint",
                "Block or restrict the identified malicious source",
                "Preserve relevant logs for forensics",
                "Monitor resource utilization",
                "Restore affected service capacity",
                "Continue monitoring for repeated requests",
            ]
        elif cat in ("ransomware", "malware"):
            actions = [
                "Isolate affected hosts immediately",
                "Block lateral movement paths",
                "Preserve encrypted file samples and ransom notes",
                "Scan adjacent systems for indicators",
                "Prepare for recovery from clean backups",
                "Notify incident response team",
            ]
        elif cat in ("sql_injection", "sql-injection"):
            actions = [
                "Block malicious source IP at WAF/firewall",
                "Disable or restrict vulnerable endpoint",
                "Review database access logs for data exfiltration",
                "Apply input validation patches",
                "Audit database for unauthorized modifications",
            ]
        elif cat in ("credential_theft", "credential-theft", "brute_force"):
            actions = [
                "Lock compromised accounts",
                "Revoke active tokens and sessions",
                "Force password reset for affected accounts",
                "Enable MFA if not already active",
                "Review login audit trail",
            ]
        elif cat in ("recon", "reconnaissance"):
            actions = [
                "Block scanning source IP",
                "Review firewall and IDS rules",
                "Audit exposed services",
                "Strengthen network segmentation",
            ]
        else:
            actions = [
                "Isolate affected systems",
                "Preserve evidence and logs",
                "Review access controls",
                "Notify security operations team",
            ]
        return actions
